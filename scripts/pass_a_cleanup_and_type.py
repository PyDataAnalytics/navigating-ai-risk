def _bidir(pairs: Iterable[tuple[str, str]]) -> set[tuple[str, str]]:
    """Make pair set bidirectional so order doesn't matter at lookup."""
    s = set(pairs)
    return s | {(b, a) for (a, b) in s}


CROSS_CAT_SIMILAR_PAIRS = _bidir(_CROSS_CAT_SIMILAR_BASE)
SAME_CAT_RELATED_PAIRS = _bidir(_SAME_CAT_RELATED_BASE)


# ---------------------------------------------------------------------------
# Symmetry enforcement: for every (A, B) classified as similar, ensure (B, A)
# is also classified as similar. The 'similar' relation is intrinsically
# symmetric — A is similar to B iff B is similar to A.
#
# This is run AFTER typing in Step 2, before the file is emitted. If the file
# already has both directions present, this is a no-op.
# ---------------------------------------------------------------------------


def _enforce_symmetry(defs: dict) -> tuple[int, int]:
    """Add reverse-direction edges where missing. Returns (added, demoted).

    'added' = new similar edges added in the reverse direction.
    'demoted' = edges previously in `related` that needed to flip to `similar`
                because their reverse direction is in `similar`.
    """
    by_name = {sc["name"]: sc for sc in defs["subcategories"]}
    added = 0
    demoted = 0

    # First pass: collect all directed similar edges
    forward_similar: set[tuple[str, str]] = set()
    for sc in defs["subcategories"]:
        for sib in sc["adjacent_to"]["similar"]:
            forward_similar.add((sc["name"], sib))

    # For every (A, B) in similar, ensure (B, A) is also in similar
    for a, b in forward_similar:
        if (b, a) in forward_similar:
            continue  # already symmetric
        rev_entry = by_name[b]
        # If a is currently in b's `related`, demote (remove from related, add to similar)
        if a in rev_entry["adjacent_to"]["related"]:
            rev_entry["adjacent_to"]["related"].remove(a)
            demoted += 1
        # Add a to b's similar (idempotent: skip if already there for any reason)
        if a not in rev_entry["adjacent_to"]["similar"]:
            rev_entry["adjacent_to"]["similar"].append(a)
            added += 1

    return added, demoted


# ---------------------------------------------------------------------------
# Idempotency: flatten any existing typed structure back to a list
# ---------------------------------------------------------------------------


def _flatten_adjacent_to(adj) -> list[str]:
    """Accept either the typed dict form or the flat list form, return flat list."""
    if isinstance(adj, list):
        return list(adj)
    if isinstance(adj, dict):
        return list(adj.get("similar", [])) + list(adj.get("related", []))
    return []



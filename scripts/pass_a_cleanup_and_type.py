def main() -> int:
    defs = yaml.safe_load(DEFS_PATH.read_text())
    taxonomy = yaml.safe_load(TAXONOMY_PATH.read_text())

    canonical = {sub["name"] for cat in taxonomy["categories"] for sub in cat["subcategories"]}
    sub_to_cat = {
        sub["name"]: cat["name"] for cat in taxonomy["categories"] for sub in cat["subcategories"]
    }

    # ----- Step 1: flatten any prior typed form, then clean -----
    broken_dropped = 0
    broken_mapped = 0
    self_loops_removed = 0

    for sc in defs["subcategories"]:
        name = sc["name"]
        adj = _flatten_adjacent_to(sc.get("adjacent_to", []))
        new_adj: list[str] = []
        for a in adj:
            if a == name:
                self_loops_removed += 1
                continue
            if a not in canonical:
                action = BROKEN_REF_MAP.get(a)
                if action == "drop":
                    broken_dropped += 1
                    continue
                if action and action.startswith("map:"):
                    mapped = action.split(":", 1)[1]
                    if mapped not in canonical:
                        raise ValueError(f"Override target {mapped!r} not canonical")
                    if mapped in new_adj or mapped == name:
                        broken_dropped += 1
                        continue
                    new_adj.append(mapped)
                    broken_mapped += 1
                    continue
                raise ValueError(f"Unmapped broken ref {a!r} in entry {name!r}")
            if a in new_adj:
                continue
            new_adj.append(a)
        sc["_adj_flat"] = new_adj  # stash for step 2

    # ----- Step 2: type each edge -----
    def classify(src: str, tgt: str) -> str:
        pair = (src, tgt)
        if pair in CROSS_CAT_SIMILAR_PAIRS:
            return "similar"
        if pair in SAME_CAT_RELATED_PAIRS:
            return "related"
        return "similar" if sub_to_cat[src] == sub_to_cat[tgt] else "related"

    similar_count = 0
    related_count = 0
    for sc in defs["subcategories"]:
        src = sc["name"]
        sim: list[str] = []
        rel: list[str] = []
        for tgt in sc.pop("_adj_flat"):
            if classify(src, tgt) == "similar":
                sim.append(tgt)
                similar_count += 1
            else:
                rel.append(tgt)
                related_count += 1
        sc["adjacent_to"] = {"similar": sim, "related": rel}

    # ----- Step 2b: enforce symmetry on similar edges -----
    sym_added, sym_demoted = _enforce_symmetry(defs)
    similar_count += sym_added
    related_count -= sym_demoted

    # ----- Step 3: emit canonical YAML (preserve grouping by category) -----
    cat_boundaries = []
    idx = 0
    for cat in taxonomy["categories"]:
        start = idx
        idx += len(cat["subcategories"])
        cat_boundaries.append((start, idx, cat["name"]))

    _write_yaml(defs, cat_boundaries)

    # ----- Report -----
    print(f"Step 1: broken refs dropped: {broken_dropped}")
    print(f"Step 1: broken refs mapped:  {broken_mapped}")
    print(f"Step 1: self-loops removed:  {self_loops_removed}")
    print(f"Step 2: edges typed:         {similar_count + related_count}")
    print(f"           similar:          {similar_count}")
    print(f"           related:          {related_count}")
    print(f"Step 2b: symmetry added:     {sym_added}")
    print(f"Step 2b: symmetry demoted:   {sym_demoted}")
    return 0


def _emit_entry(entry: dict, indent: str = "  ") -> str:
    lines = [
        f'{indent}- name: "{entry["name"]}"',
        f"{indent}  nature: {entry['nature']}",
        f"{indent}  confidence: {entry['confidence']}",
        f'{indent}  one_line: "{entry["one_line"].replace(chr(34), chr(92) + chr(34))}"',
    ]
    for field in ("applies_when", "does_not_apply_when", "user_signals"):
        lines.append(f"{indent}  {field}:")
        for item in entry[field]:
            esc = item.replace('"', '\\"')
            lines.append(f'{indent}    - "{esc}"')
    lines.append(f"{indent}  adjacent_to:")
    for rel_key in ("similar", "related"):
        items = entry["adjacent_to"].get(rel_key, [])
        if items:
            lines.append(f"{indent}    {rel_key}:")
            for item in items:
                esc = item.replace('"', '\\"')
                lines.append(f'{indent}      - "{esc}"')
        else:
            lines.append(f"{indent}    {rel_key}: []")
    # Preserve disambiguation field if Pass B has already populated it.
    # Pass A doesn't manage disambiguation content, but must not drop it on re-emit.
    disambig = entry.get("disambiguation")
    if isinstance(disambig, dict) and disambig:
        lines.append(f"{indent}  disambiguation:")
        for sibling in entry["adjacent_to"]["similar"]:
            if sibling in disambig:
                key_esc = sibling.replace('"', '\\"')
                val_esc = disambig[sibling].replace('"', '\\"')
                lines.append(f'{indent}    "{key_esc}": "{val_esc}"')
    lines.append(f"{indent}  elements:")
    for elem in (
        "threat",
        "event",
        "operational_artifacts",
        "mitigations_controls",
        "regulatory_standards",
        "research",
    ):
        e = entry["elements"][elem]
        lines.append(f"{indent}    {elem}:")
        lines.append(f"{indent}      population: {e['population']}")
        if "notes" in e:
            notes = e["notes"].replace('"', '\\"')
            lines.append(f'{indent}      notes: "{notes}"')
    return "\n".join(lines)


def _write_yaml(defs: dict, cat_boundaries: list[tuple[int, int, str]]) -> None:
    header = (
        "# AI Risk Taxonomy — Subcategory Definitions (v2.1)\n"
        "# =====================================================\n"
        "# Expert-revised v2 with: nature, confidence, applies_when, does_not_apply_when,\n"
        "# user_signals, adjacent_to (typed: similar / related), and elements (6 populations).\n"
        "#\n"
        "# adjacent_to.similar: close concepts the matcher might consider switching to\n"
        "# adjacent_to.related: connected but distinct concepts the matcher might mention\n"
        "#\n"
        "# Names match taxonomy.yaml exactly — this is the interface contract.\n"
        "#\n"
        "# Version: 2.1\n"
        "\n"
        'version: "2.1"\n'
    )
    out = [header, "subcategories:", ""]
    for start, end, title in cat_boundaries:
        out.append("  # " + "═" * 68)
        out.append(f"  # {title}")
        out.append("  # " + "═" * 68)
        out.append("")
        for i in range(start, end):
            out.append(_emit_entry(defs["subcategories"][i]))
            out.append("")
    DEFS_PATH.write_text("\n".join(out))


